#!/usr/bin/env python3
"""Embeds the HLSL sources into ../kt_shaders_gen.h (common.hlsli inlined). Run after editing a shader."""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
common = open(os.path.join(here, 'common.hlsli')).read()
out = ['// generated by shaders/gen.py - do not edit', '#pragma once', '']
for f in sorted(os.listdir(here)):
    if not f.endswith('.hlsl'):
        continue
    src = open(os.path.join(here, f)).read().replace('#include "common.hlsli"', common)
    name = 'kt_src_' + f[:-5]
    # MSVC limits string literals to ~16K: split into chunks
    chunks = [src[i:i + 12000] for i in range(0, len(src), 12000)]
    out.append('static const char* const %s_parts[] = {' % name)
    for c in chunks:
        out.append('R"KTSRC(%s)KTSRC",' % c)
    out.append('nullptr };')
out.append('')
open(os.path.join(here, '..', 'kt_shaders_gen.h'), 'w').write('\n'.join(out))
print('wrote kt_shaders_gen.h')
